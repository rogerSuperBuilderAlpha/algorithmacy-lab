#!/usr/bin/env python3
"""Build INDEX.md for the DXD animator card library, grouped by pillar. Stdlib only.
    python submissions/dxd_animator/literature/library/build_index.py [--check]"""
import pathlib, re, sys
HERE = pathlib.Path(__file__).resolve().parent
PILLARS = ["Pillar 1", "Pillar 2", "Pillar 3"]
def build():
    groups, n = {}, 0
    for f in sorted((HERE / "cards").glob("*.md")):
        t = f.read_text()
        ref = re.sub(r"^#\s*", "", t.splitlines()[0]).strip()
        p = re.search(r"\*\*Pillar:\*\*\s*([^·\n]+)", t)
        c = re.search(r"\*\*Citation count:\*\*\s*([^·\n]+)", t)
        if not (p and c and "## What it argues" in t and "## Relation to the argument" in t):
            sys.exit(f"bad card: {f.name}")
        short = ref if len(ref) <= 170 else ref[:167].rsplit(" ", 1)[0] + "…"
        groups.setdefault(p.group(1).strip(), []).append(f"- [{short}](cards/{f.name}) — cites: {c.group(1).strip()}")
        n += 1
    out = ["# DXD animator library — index", "",
           "*Generated by `build_index.py`; do not edit by hand. Agent-written cards; the author has not reviewed them.*", "",
           f"{n} cards. Every card is marked ⚠ Not read in full: summaries rest on abstracts and catalogue records.", ""]
    for g in sorted(groups):
        out += [f"## {g} ({len(groups[g])})", ""] + groups[g] + [""]
    return "\n".join(out), n
text, n = build()
idx = HERE / "INDEX.md"
if "--check" in sys.argv:
    if not idx.exists() or idx.read_text() != text:
        sys.exit("INDEX.md is stale; run build_index.py")
    print(f"dxd animator library OK ({n} cards)")
else:
    idx.write_text(text); print(f"wrote INDEX.md ({n} cards)")
