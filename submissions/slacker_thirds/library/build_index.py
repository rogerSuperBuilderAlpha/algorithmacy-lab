#!/usr/bin/env python3
"""Generate CARDS_INDEX.md for the Slacker-chapter source library from the per-source cards.

Deterministic: output depends only on the card files on disk (sorted). Modeled on
org_frontier/research/build_cards_index.py (via hegel_coordination).

    python build_index.py           # rewrite CARDS_INDEX.md
    python build_index.py --check   # exit 1 if CARDS_INDEX.md is stale or a card is malformed
"""
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CARDS = os.path.join(HERE, "cards")
INDEX = os.path.join(HERE, "CARDS_INDEX.md")


def frontmatter(path):
    fm = {}
    with open(path, encoding="utf-8") as f:
        text = f.read()
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        return fm
    for line in m.group(1).splitlines():
        mm = re.match(r"([A-Za-z_]+):\s*(.*)$", line)
        if mm:
            fm[mm.group(1)] = mm.group(2).strip().strip('"')
    return fm


def build():
    cs = sorted(glob.glob(os.path.join(CARDS, "*.md")))
    L = [
        "# Slacker-chapter source library — card index",
        "",
        "*Generated by `build_index.py`. Do not edit by hand — edits are overwritten.*",
        "",
        "One card per source bearing on the chapter. `domain` is the knowledge domain the source belongs to; "
        "`used_by` lists the chapter sections or footnotes that draw on it; `status` is `cited` (in the "
        "live chapter), `held` (in the library, not yet cited), or `candidate` (surfaced by the deep "
        "research pass as worth citing). See [`REFERENCES.md`](REFERENCES.md) for the Chicago master "
        "bibliography and [`domains/`](domains/) for the per-domain audits.",
        "",
    ]
    if not cs:
        L += ["*No cards yet.*", ""]
        return "\n".join(L).rstrip() + "\n"
    malformed = []
    L += [f"**{len(cs)} cards.**", "",
          "| citekey | title | year | domain | used by | status | verified |",
          "|---|---|---|---|---|---|---|"]
    for c in cs:
        fm = frontmatter(c)
        ck = fm.get("citekey", os.path.basename(c)[:-3])
        if not fm.get("citekey") or not fm.get("verified"):
            malformed.append(os.path.basename(c))
        title = (fm.get("title", "") or "").replace("|", "\\|")
        if len(title) > 70:
            title = title[:67] + "…"
        year = fm.get("year", "—")
        domain = (fm.get("domain", "") or "—").replace("|", "/")
        used = (fm.get("used_by", "") or "—").replace("|", "/")
        if len(used) > 34:
            used = used[:31] + "…"
        status = fm.get("status", "—")
        ver = fm.get("verified", "—")
        L.append(f"| [{ck}](cards/{os.path.basename(c)}) | {title} | {year} | {domain} | {used} | {status} | {ver} |")
    out = "\n".join(L).rstrip() + "\n"
    return out, malformed


def main():
    res = build()
    if isinstance(res, tuple):
        out, malformed = res
    else:
        out, malformed = res, []
    check = "--check" in sys.argv
    if check:
        cur = open(INDEX).read() if os.path.exists(INDEX) else ""
        stale = cur != out
        if malformed:
            print("MALFORMED cards (missing citekey/verified):", ", ".join(malformed))
        if stale:
            print("CARDS_INDEX.md is STALE — run build_index.py")
        sys.exit(1 if (stale or malformed) else 0)
    with open(INDEX, "w") as f:
        f.write(out)
    print(f"wrote {INDEX}")
    if malformed:
        print("WARNING malformed cards:", ", ".join(malformed))


if __name__ == "__main__":
    main()
