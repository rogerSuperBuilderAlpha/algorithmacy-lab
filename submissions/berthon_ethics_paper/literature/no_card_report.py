#!/usr/bin/env python3
"""Match the DXD Part 2 cited keys to cards in any lab library; copy matched dxd_foundation and
algorithmacy_scaffolding cards; write NO_CARD.md for cited works with no card anywhere.

    python3 -I literature/no_card_report.py          # copy matched cards, write NO_CARD.md
    python3 -I literature/no_card_report.py --check  # exit 1 if NO_CARD.md or the copies are stale

Matching: exact filename key, then normalized DOI. No stub cards are created.
"""
import glob
import os
import re
import shutil
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cardlib as cl  # noqa: E402

PART2 = os.path.join(cl.HERE, "dxd_part2")


def library_records(origin_rel, sub):
    d = os.path.join(cl.SUBMISSIONS, os.path.relpath(origin_rel, "submissions"))
    recs = []
    for p in sorted(glob.glob(os.path.join(d, "*.md"))):
        if os.path.basename(p) in cl.NONCARDS:
            continue
        r = cl.parse_card(p, sub)
        r["path"] = p
        recs.append(r)
    return recs


def audit_rows():
    rows = {}
    for p in sorted(glob.glob(os.path.join(PART2, "audit", "AUDIT_0*.md"))):
        with open(p, encoding="utf-8") as f:
            for line in f:
                m = re.match(r"\|\s*([A-Za-z0-9_\-]+)\s*\|(.*)\|\s*$", line)
                if m and m.group(1) not in ("key", "---"):
                    rows.setdefault(m.group(1), []).append((os.path.basename(p), m.group(2).strip()))
    return rows


def facet_of(key):
    hits = []
    for p in sorted(glob.glob(os.path.join(PART2, "facets", "*.bib"))):
        with open(p, encoding="utf-8") as f:
            if re.search(r"@\w+\s*\{\s*" + re.escape(key) + r"\s*,", f.read()):
                hits.append(os.path.basename(p)[:1])
    return ",".join(hits)


def main(check):
    src = cl.sources()["cards"]
    with open(os.path.join(PART2, "cited_keys.txt"), encoding="utf-8") as f:
        keys = [k.strip() for k in f if k.strip()]
    bib = cl.parse_bib(os.path.join(PART2, "references.bib"))
    libs = {sub: library_records(meta["origin"], sub) for sub, meta in src.items()}
    by_key = {(sub, r["key"]): r for sub, rs in libs.items() for r in rs}
    by_file = {(sub, r["file"][:-3]): r for sub, rs in libs.items() for r in rs}
    by_doi = {}
    for sub, rs in libs.items():
        for r in rs:
            if r["doi"]:
                by_doi.setdefault(r["doi"], []).append(r)
    audits = audit_rows()

    matched, unmatched = [], []
    for k in keys:
        doi = cl.norm_doi(bib.get(k, {}).get("doi", ""))
        hits = [by_key.get((s, k)) or by_file.get((s, k)) for s in libs]
        hits = [h for h in hits if h]
        if doi:
            hits += [h for h in by_doi.get(doi, []) if h not in hits]
        (matched if hits else unmatched).append((k, doi, hits))

    ok = True
    copied = set()
    for k, doi, hits in matched:
        for h in hits:
            if src[h["subfolder"]]["mode"] != "matched":
                continue
            dest_dir = os.path.join(cl.CARDS, h["subfolder"])
            dest = os.path.join(dest_dir, h["file"])
            copied.add(dest)
            if check:
                ok &= os.path.exists(dest) and cl.sha256(dest) == cl.sha256(h["path"])
            else:
                os.makedirs(dest_dir, exist_ok=True)
                shutil.copy2(h["path"], dest)

    lines = [
        "# Works cited in DXD Part 2 that have no card in any lab library",
        "",
        "Generated by `literature/no_card_report.py` from `dxd_part2/cited_keys.txt`, `dxd_part2/references.bib`",
        "and `dxd_part2/audit/AUDIT_0*.md`. A cited key counts as carded if a card in berthon_ethics_course,",
        "algorithmacy_design_ethics, dxd_foundation or algorithmacy_scaffolding has the same key or DOI.",
        "The audit cells are copied verbatim. No card was written for any of these works.",
        "",
        f"Cited keys: {len(keys)}. Carded: {len(matched)}. No card: {len(unmatched)}. "
        f"dxd_foundation/scaffolding cards copied for matches: {len(copied)}.",
        "",
        "## No card",
        "",
        "| key | authors | year | title | venue | DOI | facet | audit file | audit row(s), every audit that lists the key (bib status \\| claim status \\| fix) |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for k, doi, _ in unmatched:
        b = bib.get(k, {})
        venue = b.get("journal") or b.get("booktitle") or b.get("publisher") or b.get("howpublished", "")
        found = audits.get(k, [("", "not in audit")])
        af = "; ".join(a for a, _ in found)
        arow = " // ".join(f"[{a}] {r}" if len(found) > 1 else r for a, r in found)
        lines.append("| " + " | ".join(cl.md_cell(x) for x in [
            k, b.get("author", "(not in bib)"), b.get("year", ""), b.get("title", ""), venue, doi,
            facet_of(k), af, arow]) + " |")
    lines += ["", "## Carded (key → card)", "", "| key | card(s) |", "|---|---|"]
    for k, doi, hits in matched:
        lines.append(f"| {k} | " + "; ".join(f"`cards/{h['subfolder']}/{h['file']}`" for h in hits) + " |")
    content = "\n".join(lines) + "\n"
    ok &= cl.write_or_check(os.path.join(cl.HERE, "NO_CARD.md"), content, check)
    print(f"cited {len(keys)}  carded {len(matched)}  no-card {len(unmatched)}  copied {len(copied)}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
