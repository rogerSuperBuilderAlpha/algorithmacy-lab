#!/usr/bin/env python3
"""Generate literature/CARD_INDEX.md: one table over every card in literature/cards/<subfolder>/.

Generalizes berthon_ethics_course/literature/build_cards_index.py to the two card formats (see cardlib).
Deterministic: output depends only on the card files on disk.

    python3 -I literature/build_cards_index.py          # rewrite CARD_INDEX.md
    python3 -I literature/build_cards_index.py --check  # exit 1 if CARD_INDEX.md is stale
"""
import collections
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cardlib as cl  # noqa: E402

WEAK = {"abstract", "secondary", "adapted", "record", "reviews/secondary"}


def flags(r):
    f = []
    if r["basis"] in WEAK:
        f.append(r["basis"])
    v = r["verified"].lower()
    if v in ("pending", "") and r["format"] == "Y":
        f.append("unverified")
    if "could not verify" in v:
        f.append("S2-unverified")
    if not r["basis"]:
        f.append("basis?")
    return ", ".join(f)


def main(check):
    cards = cl.all_cards()
    per_sub = collections.Counter(r["subfolder"] for r in cards)
    basis = collections.Counter(r["basis"] or "?" for r in cards)
    lines = [
        "# Card index (all libraries)",
        "",
        "Generated by `literature/build_cards_index.py`; do not edit by hand. Cards are byte-identical copies",
        "from their origin arms (see `../PROVENANCE.md`); fields are parsed from each card's header.",
        "Basis is normalized: full, partial, abstract, secondary, adapted. Verified is the card's own",
        "field (Y format) or its S2 verdict (H format). Flags mark abstract-only, secondary, unverified cards.",
        "",
        f"Cards: {len(cards)} — " + ", ".join(f"{k} {v}" for k, v in sorted(per_sub.items())) + ".",
        "Basis: " + ", ".join(f"{k} {v}" for k, v in sorted(basis.items())) + ".",
        "",
    ]
    for sub in sorted(per_sub):
        lines += [f"## {sub} ({per_sub[sub]})", "",
                  "| card | authors | year | title | DOI | basis | verified | flags |",
                  "|---|---|---|---|---|---|---|---|"]
        for r in cards:
            if r["subfolder"] != sub:
                continue
            lines.append("| " + " | ".join(cl.md_cell(x) for x in [
                f"[{r['file'][:-3]}](cards/{sub}/{r['file']})", r["authors"][:60], r["year"],
                r["title"][:90], r["doi"], r["basis"], r["verified"][:30], flags(r)]) + " |")
        lines.append("")
    ok = cl.write_or_check(os.path.join(cl.HERE, "CARD_INDEX.md"), "\n".join(lines), check)
    print(f"{len(cards)} cards indexed" + ("" if ok else " — CARD_INDEX.md is stale"))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
