#!/usr/bin/env python3
"""Generate ../PROVENANCE.md: every copied file in this arm, its origin, the origin's last commit, and
whether the copy is still byte-identical to the origin (sha256).

    python3 -I literature/build_provenance.py          # rewrite PROVENANCE.md
    python3 -I literature/build_provenance.py --check  # exit 1 if any copy differs or PROVENANCE.md is stale
"""
import glob
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cardlib as cl  # noqa: E402

REPO = os.path.dirname(cl.SUBMISSIONS)


def last_commit(path):
    r = subprocess.run(["git", "-C", REPO, "log", "-1", "--format=%h", "--", path],
                       capture_output=True, text=True)
    return r.stdout.strip() or "uncommitted"


def pairs():
    meta = cl.sources()
    out = []
    for dest, origin in list(meta["sources"].items()) + list(meta.get("nadella_sources", {}).items()):
        out.append((dest, origin))
    for name in sorted(os.listdir(os.path.join(cl.ARM, "sources", "notes"))):
        origin = None
        for prefix, base in meta["notes_prefixes"].items():
            if name == prefix:
                origin = base
                break
            if name.startswith(prefix) and prefix.endswith("_") and base.endswith("/"):
                origin = base + name[len(prefix):]
                break
        out.append((f"sources/notes/{name}", origin))
    for sub, m in meta["cards"].items():
        for p in sorted(glob.glob(os.path.join(cl.CARDS, sub, "*"))):
            out.append((f"literature/cards/{sub}/{os.path.basename(p)}", f"{m['origin']}/{os.path.basename(p)}"))
    for dest, origin in meta["dirs"].items():
        for p in sorted(glob.glob(os.path.join(cl.ARM, dest, "**", "*"), recursive=True)):
            if os.path.isfile(p):
                rel = os.path.relpath(p, os.path.join(cl.ARM, dest))
                out.append((f"{dest}/{rel}", f"{origin}/{rel}"))
    return out


def main(check):
    rows, bad = [], []
    for dest, origin in pairs():
        dp = os.path.join(cl.ARM, dest)
        op = os.path.join(REPO, origin) if origin else None
        if not op or not os.path.exists(op):
            same, commit = "ORIGIN MISSING", "—"
        else:
            same = "yes" if cl.sha256(dp) == cl.sha256(op) else "NO"
            commit = last_commit(origin)
        if same != "yes":
            bad.append(dest)
        rows.append(f"| `{dest}` | `{origin}` | {commit} | {cl.sha256(dp)[:12]} | {same} |")
    lines = ["# Provenance of copied files", "",
             "Generated by `literature/build_provenance.py`; do not edit by hand. Every file below is a copy;",
             "the origin stays where it was. \"Identical\" compares sha256 of copy and origin at build time.",
             "", f"Files: {len(rows)}. Not identical or origin missing: {len(bad)}.", "",
             "| copy | origin | origin last commit | sha256 (12) | identical |", "|---|---|---|---|---|"] + rows
    ok = cl.write_or_check(os.path.join(cl.ARM, "PROVENANCE.md"), "\n".join(lines) + "\n", check) and not bad
    print(f"{len(rows)} copies; {len(bad)} differ" + ("" if not bad else ": " + ", ".join(bad[:10])))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
