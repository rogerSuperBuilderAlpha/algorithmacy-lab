#!/usr/bin/env python3
"""Generate literature/DUPLICATES.md: cards in different libraries that describe the same work.

Clusters by (1) normalized DOI, (2) first six title words + year, (3) identical filename. Recommends a
primary card per cluster: deeper read > checked against a manuscript line (Y format) > ties go to
berthon_ethics_course. Cards are never merged; read both before relying on either.

    python3 -I literature/dedup_report.py          # rewrite DUPLICATES.md
    python3 -I literature/dedup_report.py --check  # exit 1 if stale
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cardlib as cl  # noqa: E402

DEPTH = {"full": 4, "partial": 3, "adapted": 2, "abstract": 1, "secondary": 1}
SUBRANK = {"berthon_ethics_course": 3, "algorithmacy_design_ethics": 2, "dxd_foundation": 1}


def rank(r):
    return (DEPTH.get(r["basis"], 0), 1 if r["format"] == "Y" else 0, SUBRANK.get(r["subfolder"], 0))


def main(check):
    cards = cl.all_cards()
    n = len(cards)
    parent = list(range(n))

    def find(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i

    reasons = {}
    for label, keyf in [("DOI", lambda r: r["doi"]),
                        ("title+year", lambda r: cl.norm_title(r["title"], r["year"]) if r["year"] else ""),
                        ("filename", lambda r: r["file"])]:
        seen = {}
        for i, r in enumerate(cards):
            k = keyf(r)
            if not k:
                continue
            if k in seen and cards[seen[k]]["subfolder"] != r["subfolder"]:
                a, b = find(seen[k]), find(i)
                if a != b:
                    parent[b] = a
                reasons.setdefault(find(i), set()).add(label)
            seen.setdefault(k, i)
    clusters = {}
    for i in range(n):
        clusters.setdefault(find(i), []).append(i)
    multi = [sorted(v, key=lambda i: (cards[i]["subfolder"], cards[i]["file"]))
             for v in clusters.values() if len({cards[i]["subfolder"] for i in v}) > 1]
    multi.sort(key=lambda v: cards[v[0]]["file"])
    lines = ["# Duplicate cards across libraries", "",
             "Generated by `literature/dedup_report.py`; do not edit by hand. Each cluster is one work carded",
             "in more than one library. The primary is a recommendation by read depth; it is not a merge, and",
             "substantive disagreements between cards are recorded by hand in `../consolidation/CONFLICTS.md`.",
             "", f"Clusters: {len(multi)}.", "",
             "| # | matched by | primary | other card(s) |", "|---|---|---|---|"]
    for k, v in enumerate(multi, 1):
        root = find(v[0])
        best = max(v, key=lambda i: rank(cards[i]))

        def show(i):
            r = cards[i]
            return f"`{r['subfolder']}/{r['file']}` ({r['basis'] or '?'}; {r['verified'][:24] or '—'})"
        others = "; ".join(show(i) for i in v if i != best)
        lines.append(f"| {k} | {', '.join(sorted(reasons.get(root, {'?'})))} | {show(best)} | {others} |")
    ok = cl.write_or_check(os.path.join(cl.HERE, "DUPLICATES.md"), "\n".join(lines) + "\n", check)
    print(f"{len(multi)} duplicate clusters" + ("" if ok else " — DUPLICATES.md is stale"))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
