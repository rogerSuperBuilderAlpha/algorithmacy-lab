#!/usr/bin/env python3
"""Coverage check for the consolidation: nothing in the eight versions or their audits goes unmapped.

    python3 -I consolidation/coverage_check.py --headings  # (re)write HEADINGS.md, keeping filled ID cells
    python3 -I consolidation/coverage_check.py             # write COVERAGE.md; exit 1 on any gap
    python3 -I consolidation/coverage_check.py --check     # also exit 1 if COVERAGE.md is stale

Conventions in the hand-written files (CONCEPT_LEDGER.md, CONFLICTS.md, CONSOLIDATION.md):
- Ledger rows open "| K01 |" (prefixes K H N E D O L M P). Conflicts open "### X01".
- Cards are cited in backticks by short path: `bec/<file>.md`, `ade/<file>.md`, `dxf/<file>.md`,
  `scf/<file>.md` (berthon_ethics_course, algorithmacy_design_ethics, dxd_foundation,
  algorithmacy_scaffolding). Works with no card: `nocard:<key>`.
- Audit items are cited as tokens: CHK-A1 (AUTHOR_DRAFT_CHECK rows), V4N-1 (V4_NOTES departures),
  TADJ-3.1 / TADJ-6.1 (T_adjudication §3 items, §6 decisions), REV-F1 / REV-A1 (REVIEW_SUMMARY fix
  items and argument items), BN-1.1 (BERTHON_NOTES §1 rows), ADA-2.1 / ADA-4.1 (ADE DRAFT_AUDIT
  buckets 2 and 4), and the v3 change ids themselves (P1-002, ASM-2, FC2-17, R01 ...).

Hard failures: a heading with no ID; an ID in HEADINGS or CONSOLIDATION that is not a ledger row; a
ledger row never cited in CONSOLIDATION; a cited card path that does not exist; a `nocard:` key not in
NO_CARD.md; an audit item or AUTHOR-marked v3 change cited nowhere. Report only: orphan cards; DXD Part 2
cited keys that are neither carded in the ledger nor named.
"""
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ARM = os.path.dirname(HERE)
SRC = os.path.join(ARM, "sources")
NOTES = os.path.join(SRC, "notes")
CARDS = os.path.join(ARM, "literature", "cards")
SHORT = {"bec": "berthon_ethics_course", "ade": "algorithmacy_design_ethics",
         "dxf": "dxd_foundation", "scf": "algorithmacy_scaffolding"}
VERSIONS = sorted(os.path.basename(p) for p in glob.glob(os.path.join(SRC, "0*.md")))
ID_RE = re.compile(r"\b([KHNEDOLMP]\d{2})\b")


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


# ---------- headings ----------
def headings(fname):
    out = []
    plain = fname.startswith(("04_", "05_"))
    in_code = False
    for n, line in enumerate(read(os.path.join(SRC, fname)).splitlines(), 1):
        if line.startswith("```"):
            in_code = not in_code
        if in_code:
            continue
        if not plain:
            m = re.match(r"^(#{1,4})\s+(.*)", line)
            if m:
                out.append((n, m.group(2).strip()))
        elif (len(line) <= 130 and not re.search(r"([;.]| or)$", line)
              and re.match(r"^(§?\d+(\.\d+)?\.? [A-Z]|Abstract$|Introduction$|References|Restructured Outline$|Algorithmacy: )", line)):
            out.append((n, line.strip()))
    return out


def existing_heading_ids():
    path = os.path.join(HERE, "HEADINGS.md")
    ids = {}
    if os.path.exists(path):
        for line in read(path).splitlines():
            m = re.match(r"\|\s*(\S+)\s*\|\s*(\d+)\s*\|.*\|\s*([^|]*)\|\s*$", line)
            if m:
                ids[(m.group(1), int(m.group(2)))] = m.group(3).strip()
    return ids


def write_headings():
    keep = existing_heading_ids()
    lines = ["# Headings of the eight versions, mapped to ledger rows", "",
             "Generated by `coverage_check.py --headings` (markdown headings; for the two author drafts, which",
             "have none, the numbered section lines). The last column is filled by hand with the ledger IDs",
             "each section carries; `REFS` marks a reference list and `TITLE` a title line. Re-running",
             "`--headings` keeps filled cells.", "",
             "| file | line | heading | ledger IDs |", "|---|---|---|---|"]
    for v in VERSIONS:
        for n, h in headings(v):
            cell = keep.get((v, n), "")
            lines.append(f"| {v} | {n} | {h.replace('|', '/')} | {cell} |")
    with open(os.path.join(HERE, "HEADINGS.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"HEADINGS.md: {sum(len(headings(v)) for v in VERSIONS)} headings")


# ---------- audit items that must be cited ----------
def required_items():
    req = {}
    chk = read(os.path.join(NOTES, "berthon_AUTHOR_DRAFT_CHECK.md"))
    for r in re.findall(r"^\| ([A-D]\d+) \|", chk, re.M):
        req[f"CHK-{r}"] = "AUTHOR_DRAFT_CHECK row"
    v4 = read(os.path.join(NOTES, "berthon_v4_V4_NOTES.md"))
    sec = v4.split("## Where v4 departs", 1)[1].split("\n## ", 1)[0]
    for r in re.findall(r"^(\d+)\. \*\*", sec, re.M):
        req[f"V4N-{r}"] = "V4_NOTES departure"
    t = read(os.path.join(NOTES, "berthon_T_adjudication.md"))
    for secno, title in (("3", "## 3."), ("6", "## 6.")):
        body = t.split(title, 1)[1].split("\n## ", 1)[0]
        for r in re.findall(r"^(\d+)\. \*\*", body, re.M):
            req[f"TADJ-{secno}.{r}"] = f"T_adjudication §{secno} item"
    rv = read(os.path.join(NOTES, "berthon_review_REVIEW_SUMMARY.md"))
    fix = rv.split("## Fix before", 1)[1].split("\n## ", 1)[0]
    arg = rv.split("## The argument", 1)[1].split("\n## ", 1)[0]
    for r in re.findall(r"^(\d+)\. \*\*", fix, re.M):
        req[f"REV-F{r}"] = "REVIEW_SUMMARY fix item"
    for r in re.findall(r"^(\d+)\. \*\*", arg, re.M):
        req[f"REV-A{r}"] = "REVIEW_SUMMARY argument item"
    for i in (1, 2, 3):
        req[f"BN-1.{i}"] = "BERTHON_NOTES §1 row"
    ada = read(os.path.join(NOTES, "ade_DRAFT_AUDIT.md"))
    for b in ("2", "4"):
        body = ada.split(f"## Bucket {b}", 1)[1].split("\n## ", 1)[0]
        for k, _ in enumerate(re.findall(r"^- \*\*", body, re.M), 1):
            req[f"ADA-{b}.{k}"] = f"ADE DRAFT_AUDIT bucket {b} item"
    v3 = read(os.path.join(SRC, "07_MANUSCRIPT_v3.md"))
    for m in re.finditer(r"<!-- v3: (.*?) -->", v3):
        for seg in m.group(1).split(";"):
            if "AUTHOR" in seg:
                for i in re.findall(r"\b(?:P\d-N?\d+|ASM-\d+|FC\d-\d+|R\d+|B\d+)\b", seg):
                    req[i] = "v3 change marked AUTHOR"
    return req


def main(check):
    ledger = read(os.path.join(HERE, "CONCEPT_LEDGER.md"))
    conflicts = read(os.path.join(HERE, "CONFLICTS.md"))
    consol = read(os.path.join(HERE, "CONSOLIDATION.md"))
    rows = re.findall(r"^\|\s*([KHNEDOLMP]\d{2})\s*\|", ledger, re.M)
    rowset = set(rows)
    fails, report = [], []

    dup = sorted({r for r in rows if rows.count(r) > 1})
    if dup:
        fails.append(f"duplicate ledger IDs: {', '.join(dup)}")

    # headings
    hids = existing_heading_ids()
    missing_h, bad_h = [], []
    for v in VERSIONS:
        for n, h in headings(v):
            cell = hids.get((v, n), "")
            if not cell:
                missing_h.append(f"{v}:{n} {h}")
                continue
            for i in ID_RE.findall(cell):
                if i not in rowset:
                    bad_h.append(f"{v}:{n} → {i}")
    if missing_h:
        fails.append(f"{len(missing_h)} headings with no ledger ID: " + "; ".join(missing_h[:15]))
    if bad_h:
        fails.append("heading IDs not in ledger: " + "; ".join(bad_h))

    # consolidation ↔ ledger
    cited = set(ID_RE.findall(consol))
    unknown = sorted(cited - rowset)
    uncited = sorted(rowset - cited)
    if unknown:
        fails.append("CONSOLIDATION cites IDs not in the ledger: " + ", ".join(unknown))
    if uncited:
        fails.append("ledger rows never cited in CONSOLIDATION: " + ", ".join(uncited))
    for i in sorted(set(ID_RE.findall(conflicts)) - rowset):
        fails.append(f"CONFLICTS cites unknown ledger ID {i}")

    # cards
    alltext = ledger + conflicts + consol
    used = set()
    for short, fname in re.findall(r"`(bec|ade|dxf|scf)/([^`]+?\.md)`", alltext):
        p = os.path.join(CARDS, SHORT[short], fname)
        used.add((SHORT[short], fname))
        if not os.path.exists(p):
            fails.append(f"card not found: {short}/{fname}")
    nocard = read(os.path.join(ARM, "literature", "NO_CARD.md"))
    for k in sorted(set(re.findall(r"`nocard:([^`]+)`", alltext))):
        if f"| {k} |" not in nocard:
            fails.append(f"nocard key not in NO_CARD.md: {k}")

    # required audit items
    req = required_items()
    missing_req = [f"{k} ({v})" for k, v in sorted(req.items())
                   if not re.search(r"(?<![\w-])" + re.escape(k) + r"(?![\w-])", ledger + conflicts)]
    if missing_req:
        fails.append(f"{len(missing_req)} audit items cited nowhere: " + "; ".join(missing_req))

    # report-only
    orphans = {}
    for sub in sorted(os.listdir(CARDS)):
        d = os.path.join(CARDS, sub)
        if not os.path.isdir(d):
            continue
        for p in sorted(glob.glob(os.path.join(d, "*.md"))):
            f = os.path.basename(p)
            if f in ("INDEX.md", "README.md") or (sub, f) in used:
                continue
            orphans.setdefault(sub, []).append(f[:-3])
    for sub, fs in orphans.items():
        report.append(f"**{sub}**: {len(fs)} cards cited in no ledger row — " + ", ".join(fs))

    lines = ["# Coverage report", "",
             "Generated by `coverage_check.py`; do not edit by hand.", "",
             f"Ledger rows: {len(rowset)}. Headings: {sum(len(headings(v)) for v in VERSIONS)}. "
             f"Required audit items: {len(req)}. Cards cited: {len(used)}.", "",
             "## Hard failures", ""] + ([f"- {x}" for x in fails] or ["None."]) + \
            ["", "## Orphan cards (information, not failure)", "",
             "A card no ledger row cites is not lost: it stays in `literature/cards/` and `CARD_INDEX.md`.",
             "Most are background the origin arms read and the versions never cited.", ""] + \
            ([f"- {x}" for x in report] or ["None."])
    content = "\n".join(lines) + "\n"
    path = os.path.join(HERE, "COVERAGE.md")
    stale = check and (not os.path.exists(path) or read(path) != content)
    if not check:
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
    print(f"{len(fails)} hard failures; ledger {len(rowset)} rows; cards cited {len(used)}"
          + ("; COVERAGE.md stale" if stale else ""))
    for x in fails:
        print("  -", x[:300])
    return 1 if (fails or stale) else 0


if __name__ == "__main__":
    if "--headings" in sys.argv:
        write_headings()
        sys.exit(0)
    sys.exit(main("--check" in sys.argv))
