#!/usr/bin/env python3
"""Generate CARDS_INDEX.md for the Hegel-series source library from the per-source cards.

Deterministic: output depends only on the card files on disk (sorted). Modeled on
org_frontier/research/build_cards_index.py.

    python build_index.py           # rewrite CARDS_INDEX.md
    python build_index.py --check   # exit 1 if CARDS_INDEX.md is stale or a card is malformed
"""
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CARDS = os.path.join(HERE, "cards")
INDEX = os.path.join(HERE, "CARDS_INDEX.md")


def frontmatter(path):
    fm = {}
    with open(path, encoding="utf-8") as f:
        text = f.read()
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        return fm
    for line in m.group(1).splitlines():
        mm = re.match(r"([A-Za-z_]+):\s*(.*)$", line)
        if mm:
            fm[mm.group(1)] = mm.group(2).strip().strip('"')
    return fm


def build():
    cs = sorted(glob.glob(os.path.join(CARDS, "*.md")))
    L = [
        "# Hegel-series source library — card index",
        "",
        "*Generated by `build_index.py`. Do not edit by hand — edits are overwritten.*",
        "",
        "One verified card per source used across the nine posts. `edition_pin` is set only for the "
        "Hegel editions the series pins. `used_by_posts` lists the posts that cite the source. See "
        "[`REFERENCES.md`](REFERENCES.md) for the APA master bibliography and "
        "[`digests/`](digests/) for the per-paper grounding digests.",
        "",
    ]
    if not cs:
        L += ["*No cards yet.*", ""]
        return "\n".join(L).rstrip() + "\n"
    malformed = []
    L += [f"**{len(cs)} cards.**", "",
          "| citekey | title | year | posts | edition pin | verified |",
          "|---|---|---|---|---|---|"]
    for c in cs:
        fm = frontmatter(c)
        ck = fm.get("citekey", os.path.basename(c)[:-3])
        if not fm.get("citekey") or not fm.get("verified"):
            malformed.append(os.path.basename(c))
        title = (fm.get("title", "") or "").replace("|", "\\|")
        if len(title) > 70:
            title = title[:67] + "…"
        year = fm.get("year", "—")
        posts = (fm.get("used_by_posts", "") or "—").replace("|", "/")
        pin = (fm.get("edition_pin", "") or "").replace("|", "/")
        if len(pin) > 34:
            pin = pin[:31] + "…"
        ver = fm.get("verified", "—")
        L.append(f"| [{ck}](cards/{os.path.basename(c)}) | {title} | {year} | {posts} | {pin} | {ver} |")
    out = "\n".join(L).rstrip() + "\n"
    return out, malformed


def main():
    res = build()
    if isinstance(res, tuple):
        out, malformed = res
    else:
        out, malformed = res, []
    check = "--check" in sys.argv
    if check:
        cur = open(INDEX).read() if os.path.exists(INDEX) else ""
        stale = cur != out
        if malformed:
            print("MALFORMED cards (missing citekey/verified):", ", ".join(malformed))
        if stale:
            print("CARDS_INDEX.md is STALE — run build_index.py")
        sys.exit(1 if (stale or malformed) else 0)
    with open(INDEX, "w") as f:
        f.write(out)
    print(f"wrote {INDEX}")
    if malformed:
        print("WARNING malformed cards:", ", ".join(malformed))


if __name__ == "__main__":
    main()
