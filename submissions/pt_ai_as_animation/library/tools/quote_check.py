#!/usr/bin/env python3
"""Check every quotation in every card's ## Loci against the local text layer of the work.

Measurement only; it writes no card prose. For each card it reads the double-quoted strings in the
`## Loci` section, loads every `.txt` in the work's folder of the local store, and reports whether the
quotation is found after whitespace, hyphenation, quote-mark and diacritic normalisation.

    python3 -I tools/quote_check.py            # writes QUOTE_CHECK.md, exit 1 on any not-found or thin-card quote
    python3 -I tools/quote_check.py KEY ...    # check only these cards, print results

Verdicts: found | found-nospace (OCR run-together) | found-partial (first and last six words found,
middle not) | not-found | no-text (no .txt in the store) | thin-card-quote (a metadata/abstract card
carries a quotation with a locator, which the rules forbid).
"""
import glob
import os
import re
import sys
import unicodedata

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_index import LIB, load  # noqa: E402

STORE = os.path.expanduser("~/iit-playground/pt_ai_animation_local/pdfs")
QUOTE = re.compile(r'["“]([^"“”\n]{12,}?)["”]')


def norm(s):
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode().lower()
    s = s.replace("­", "")
    s = re.sub(r"(\w)-\s*\n\s*(\w)", r"\1\2", s)        # hyphenated line break
    s = re.sub(r"[‘’“”'\"`]", "", s)  # quote marks of any kind
    s = re.sub(r"[–—\-]", " ", s)            # dashes and hyphens become spaces
    s = re.sub(r"[^a-z0-9 ]+", " ", s)
    return re.sub(r"\s+", " ", s).strip()


def loci_quotes(text):
    m = re.search(r"^## Loci\s*\n(.*?)(?=^## |\Z)", text, re.S | re.M)
    if not m:
        return []
    return [q.strip() for q in QUOTE.findall(m.group(1)) if len(q.split()) >= 4]


def store_text(key):
    paths = sorted(glob.glob(os.path.join(STORE, key, "*.txt")))
    return "\n".join(open(p, encoding="utf-8", errors="ignore").read() for p in paths), paths


def verdict(q, body, body_nospace):
    nq = norm(q)
    if not nq:
        return "empty"
    if nq in body:
        return "found"
    if nq.replace(" ", "") in body_nospace:
        return "found-nospace"
    w = nq.split()
    if len(w) >= 12 and " ".join(w[:6]) in body and " ".join(w[-6:]) in body:
        return "found-partial"
    return "not-found"


def main():
    only = [a for a in sys.argv[1:] if not a.startswith("-")]
    cards, _ = load()
    rows, bad = [], 0
    for c in cards:
        if only and c["key"] not in only:
            continue
        text = open(os.path.join(LIB, c["_path"]), encoding="utf-8").read()
        quotes = loci_quotes(text)
        thin = c.get("read_depth") in ("abstract", "metadata")
        if not quotes:
            rows.append((c["key"], 0, "no-quotes", ""))
            continue
        if thin:
            rows.append((c["key"], len(quotes), "thin-card-quote", quotes[0][:60]))
            bad += 1
            continue
        body, paths = store_text(c["key"])
        if not paths:
            rows.append((c["key"], len(quotes), "no-text", ""))
            bad += 1
            continue
        nb = norm(body)
        nbs = nb.replace(" ", "")
        for q in quotes:
            v = verdict(q, nb, nbs)
            if v in ("not-found", "empty"):
                bad += 1
            rows.append((c["key"], 1, v, q[:70]))
    if only:
        for r in rows:
            print("\t".join(str(x) for x in r))
        return
    counts = {}
    for r in rows:
        counts[r[2]] = counts.get(r[2], 0) + 1
    L = ["# Quotation check — card loci against the local text layer", "",
         "*Generated by `tools/quote_check.py`. Do not edit by hand.*", "",
         "Verdicts: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())) + ".", "",
         "| key | n | verdict | quotation (start) |", "|---|---|---|---|"]
    L += [f"| {k} | {n} | {v} | {q.replace('|', '/')} |" for k, n, v, q in rows]
    open(os.path.join(LIB, "QUOTE_CHECK.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    print(f"{len(rows)} rows; {bad} problems; wrote QUOTE_CHECK.md")
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
