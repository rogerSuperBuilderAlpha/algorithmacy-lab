#!/usr/bin/env python3
"""Generate CARDS_INDEX.md for the triadic-reduction talk's source library.

Deterministic: output depends only on the card files on disk (sorted). Adapted
from submissions/slacker_thirds/library/build_index.py; the card format adds a
`loci` list (what the talk or a source claims, set against what the text says).

    python3 build_index.py           # rewrite CARDS_INDEX.md
    python3 build_index.py --check   # exit 1 if CARDS_INDEX.md is stale or a card is malformed
"""
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CARDS = os.path.join(HERE, "cards")
INDEX = os.path.join(HERE, "CARDS_INDEX.md")
VERIFIED = {"verified", "corrected", "metadata-only", "unswept", "unverifiable"}


def frontmatter(path):
    fm = {}
    with open(path, encoding="utf-8") as f:
        text = f.read()
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        return fm
    for line in m.group(1).splitlines():
        mm = re.match(r"([A-Za-z_]+):\s*(.*)$", line)
        if mm:
            fm[mm.group(1)] = mm.group(2).strip().strip('"')
    return fm


def build():
    cs = sorted(glob.glob(os.path.join(CARDS, "*.md")))
    lines = [
        "# Triadic-reduction talk — source library, card index",
        "",
        "*Generated by `build_index.py`. Do not edit by hand — edits are overwritten.*",
        "",
        "One card per work the talk may cite or the preliminary sources lean on. `section` is the talk "
        "section (S1 Peirce, S2 Simmel, S3 Quine, S4 the debate, S5 the IIT move, S6 algorithmacy); "
        "`status` is `cited` (in the talk), `held` (checked, not cited) or `candidate`; `verified` is "
        "`verified` (quoted loci matched against a scan or two agreeing transcriptions), `corrected` "
        "(matched, with a correction to what a source claimed), `metadata-only` (the work exists as "
        "cited; its text was not read), `unswept` or `unverifiable`.",
        "",
    ]
    malformed = []
    if not cs:
        lines += ["*No cards yet.*", ""]
        return "\n".join(lines).rstrip() + "\n", malformed
    lines += [f"**{len(cs)} cards.**", "",
              "| citekey | title | year | section | status | verified |",
              "|---|---|---|---|---|---|"]
    for c in cs:
        fm = frontmatter(c)
        ck = fm.get("citekey", os.path.basename(c)[:-3])
        if not fm.get("citekey") or fm.get("verified") not in VERIFIED:
            malformed.append(os.path.basename(c))
        title = (fm.get("title", "") or "").replace("|", "\\|")
        if len(title) > 70:
            title = title[:67] + "…"
        lines.append(f"| [{ck}](cards/{os.path.basename(c)}) | {title} | {fm.get('year', '—')} | "
                     f"{fm.get('section', '—')} | {fm.get('status', '—')} | {fm.get('verified', '—')} |")
    return "\n".join(lines).rstrip() + "\n", malformed


def main():
    out, malformed = build()
    if "--check" in sys.argv:
        cur = open(INDEX, encoding="utf-8").read() if os.path.exists(INDEX) else ""
        stale = cur != out
        if malformed:
            print("MALFORMED cards (missing citekey or bad verified):", ", ".join(malformed))
        if stale:
            print("CARDS_INDEX.md is STALE — run build_index.py")
        sys.exit(1 if (stale or malformed) else 0)
    with open(INDEX, "w", encoding="utf-8") as f:
        f.write(out)
    print(f"wrote {INDEX}")
    if malformed:
        print("WARNING malformed cards:", ", ".join(malformed))


if __name__ == "__main__":
    main()
