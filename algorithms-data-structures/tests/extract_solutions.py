"""Pull the board solution for each problem out of source/problems.md.

Writes solutions.py, one function or class per problem, in course order, so the
tests in this folder run against exactly the code printed in the instructor key.
Two problems share a function name in the key (#136 and #260 both use
singleNumber), so the second copy of a name gets the problem number as a suffix.
Run: python3.13 -I extract_solutions.py
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parent / "source" / "problems.md"
OUT = HERE / "solutions.py"

HEADER = '''# Generated by extract_solutions.py from source/problems.md. Do not edit by hand.
import heapq
from collections import deque


class ListNode:  # LeetCode's definition
    def __init__(self, val=0, next=None):
        self.val = val
        self.next = next


class TreeNode:  # LeetCode's definition
    def __init__(self, val=0, left=None, right=None):
        self.val = val
        self.left = left
        self.right = right

'''


def problems(text):
    """Yield (number, class number, slot, code) for each problem, in order."""
    heads = list(re.finditer(r'^# .*\{\.problem number="(\d+)" classno="(\d+)" slot="([AB])"', text, re.M))
    for i, h in enumerate(heads):
        end = heads[i + 1].start() if i + 1 < len(heads) else len(text)
        body = text[h.end():end]
        key = body.split("::: key", 1)[1]
        code = re.search(r"```python\n(.*?)```", key, re.S).group(1)
        yield h.group(1), int(h.group(2)), h.group(3), code


def main():
    text = SOURCE.read_text()
    seen = set()
    chunks = [HEADER]
    count = 0
    for number, classno, slot, code in problems(text):
        lines = [ln for ln in code.splitlines() if not ln.startswith(("import ", "from "))]
        body = "\n".join(lines).strip("\n")
        name = re.match(r"(?:def|class) (\w+)", body).group(1)
        if name in seen:
            body = re.sub(rf"^(def|class) {name}\b", rf"\1 {name}_{number}", body, count=1)
        seen.add(name)
        chunks.append(f"# Class {classno}{slot}, #{number}\n{body}\n\n")
        count += 1
    OUT.write_text("\n".join(chunks))
    print(f"wrote {OUT.name}: {count} problems")
    return 0 if count == 60 else 1


if __name__ == "__main__":
    sys.exit(main())
